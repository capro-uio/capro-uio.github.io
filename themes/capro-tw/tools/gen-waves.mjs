#!/usr/bin/env node
/**
 * Generates the drifting wave path data in data/waves.yaml.
 *
 * Usage: npm run gen:waves --prefix themes/capro-tw
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const TILE = 1440;

// `periods` is a whole number so crests land on the viewBox edges, which is a
// look, not a constraint: seamlessness comes from shifting by exactly one
// period, whatever that period is.
const LAYERS = [
  { key: 1, mid: 92, amp: 22, periods: 1, phase: 0, drift: 'left' },
  { key: 2, mid: 74, amp: 28, periods: 1, phase: 180, drift: 'right' },
  { key: 3, mid: 62, amp: 18, periods: 2, phase: 90, drift: 'left' },
  { key: 4, mid: 48, amp: 24, periods: 1, phase: 400, drift: 'right' },
  { key: 5, mid: 34, amp: 14, periods: 2, phase: 260, drift: 'left' },
];

const num = (v) => String(Math.round(v * 100) / 100);

const required = (drift, shift) =>
  drift === 'left' ? [0, TILE + shift] : [-shift, TILE];

function buildPath({ mid, amp, periods, phase, drift }) {
  const shift = TILE / periods;
  const half = shift / 2;
  const [needLo, needHi] = required(drift, shift);
  const lo = needLo - half;
  const hi = needHi + half;

  const n0 = Math.floor((lo - phase) / half);
  let x = phase + n0 * half;
  // n0 is negative here, and JS takes the remainder's sign from the dividend,
  // so n0 % 2 is 0 or -1.
  let y = n0 % 2 === 0 ? mid - amp : mid + amp;

  const d = [`M${num(x)},${num(y)}`];
  while (x < hi) {
    const y2 = y < mid ? mid + amp : mid - amp;
    d.push(
      `C${num(x + half / 2)},${num(y)} ${num(x + half / 2)},${num(y2)} ${num(x + half)},${num(y2)}`,
    );
    x += half;
    y = y2;
  }
  return { d: d.join(' '), shift };
}

export function generate() {
  return LAYERS.map((L) => ({ key: L.key, drift: L.drift, ...buildPath(L) }));
}

export function toYaml(layers) {
  const lines = [
    '# Generated by tools/gen-waves.mjs -- do not edit by hand.',
    '# Run: npm run gen:waves --prefix themes/capro-tw',
    '#',
    '# A layer loops seamlessly because it is translated by exactly one period,',
    '# so it lands on itself, and because it is drawn a further period past the',
    '# viewBox on the side it drifts toward, so its trailing end stays out of',
    '# sight. The second half depends on the direction: change `drift` without',
    '# regenerating `d` and the line ends in mid-air partway through the cycle.',
    'layers:',
  ];
  for (const L of layers) {
    lines.push(`  - key: ${L.key}`);
    lines.push(`    drift: ${L.drift}`);
    lines.push(`    shift: ${L.shift}`);
    lines.push(`    d: "${L.d}"`);
  }
  return lines.join('\n') + '\n';
}

export const dataPath = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'data',
  'waves.yaml',
);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const layers = generate();
  writeFileSync(dataPath, toYaml(layers));
  console.log(`wrote ${dataPath} (${layers.length} layers)`);
}
