#!/usr/bin/env node
/**
 * Generates the drifting wave path data in data/waves.yaml.
 *
 * Each layer is a sine approximated by one cubic per half period, which puts a
 * horizontal tangent at every crest and trough. Two properties make the drift
 * loop seamlessly, and both are load-bearing:
 *
 *   1. `periods` is an integer, so the curve repeats over the 1440-unit
 *      viewBox and translating a layer by its own period maps it onto itself.
 *   2. The path is drawn past the viewBox on the side it drifts toward, far
 *      enough that its trailing endpoint never enters the visible band. A
 *      left-drifting layer therefore needs [0, 1440 + shift]; a right-drifting
 *      one needs [-shift, 1440]. A half period of margin is added on top so no
 *      layer sits flush against the boundary.
 *
 * `shift` is the layer's period, and waves.css must set --wave-shift to the
 * matching signed value. check-waves.mjs verifies all of this against the
 * committed data and stylesheet rather than trusting these comments.
 *
 * Usage: npm run gen:waves --prefix themes/capro-tw
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const TILE = 1440;

export const LAYERS = [
  { key: 1, mid: 92, amp: 22, periods: 1, phase: 0, drift: 'left' },
  { key: 2, mid: 74, amp: 28, periods: 1, phase: 180, drift: 'right' },
  { key: 3, mid: 62, amp: 18, periods: 2, phase: 90, drift: 'left' },
  { key: 4, mid: 48, amp: 24, periods: 1, phase: 400, drift: 'right' },
  { key: 5, mid: 34, amp: 14, periods: 2, phase: 260, drift: 'left' },
];

const num = (v) => {
  const r = Math.round(v * 100) / 100;
  return Number.isInteger(r) ? String(r) : String(r);
};

export function required(drift, shift) {
  return drift === 'left' ? [0, TILE + shift] : [-shift, TILE];
}

export function buildPath({ mid, amp, periods, phase, drift }) {
  const period = TILE / periods;
  const half = period / 2;
  const shift = period;
  const [needLo, needHi] = required(drift, shift);
  const lo = needLo - half;
  const hi = needHi + half;

  // Start on a half-period boundary at or below lo so the phase offset is kept
  // without leaving the leading edge short.
  const n0 = Math.floor((lo - phase) / half);
  let x = phase + n0 * half;
  // n0 is often negative, and the sign of its remainder is not portable, so
  // take the parity off the absolute value.
  let y = Math.abs(n0 % 2) === 1 ? mid + amp : mid - amp;

  const d = [`M${num(x)},${num(y)}`];
  while (x < hi) {
    const y2 = y < mid ? mid + amp : mid - amp;
    d.push(
      `C${num(x + half / 2)},${num(y)} ${num(x + half / 2)},${num(y2)} ${num(x + half)},${num(y2)}`,
    );
    x += half;
    y = y2;
  }
  return { d: d.join(' '), shift, period };
}

export function generate() {
  return LAYERS.map((L) => {
    const { d, shift, period } = buildPath(L);
    return { key: L.key, drift: L.drift, shift, period, d };
  });
}

function toYaml(layers) {
  const lines = [
    '# Generated by tools/gen-waves.mjs -- do not edit by hand.',
    '# Run: npm run gen:waves --prefix themes/capro-tw',
    '#',
    '# `drift` and `shift` belong with `d` because the path is only long enough',
    '# in one direction; changing the drift without regenerating the path leaves',
    '# a layer ending in mid-air partway through its cycle.',
    'layers:',
  ];
  for (const L of layers) {
    lines.push(`  - key: ${L.key}`);
    lines.push(`    drift: ${L.drift}`);
    lines.push(`    shift: ${L.shift}`);
    lines.push(`    d: "${L.d}"`);
  }
  return lines.join('\n') + '\n';
}

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'data', 'waves.yaml');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(out, toYaml(generate()));
  console.log(`wrote ${out} (${generate().length} layers)`);
}
